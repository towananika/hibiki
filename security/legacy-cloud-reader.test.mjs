import assert from 'node:assert/strict';
import { prepareLegacyRecords } from './legacy-records.mjs';
import { prepareArchive } from './cloud-archive.mjs';
import { makeCloudLegacyReader } from './legacy-cloud-reader.mjs';

const archive = await prepareLegacyRecords(async () => ({ value: 1 }), ['about']);
const saved = await prepareArchive(archive.archive);
const uid = 'test-owner';
let user = { uid, emailVerified: true }, calls = 0;
const reader = makeCloudLegacyReader({ currentUser: () => user, ownerUid: uid, fetchArchive: async () => { calls++; return saved; } });
assert.deepEqual(await reader.open('about'), { value: 1 });
assert.deepEqual(await reader.open('about'), { value: 1 });
assert.equal(calls, 1);
user = null;
assert.equal(await reader.open('about'), null);
user = { uid: 'other', emailVerified: true };
assert.equal(await reader.open('about'), null);
user = { uid, emailVerified: true };
assert.deepEqual(await reader.open('about'), { value: 1 });
assert.equal(calls, 2);
reader.clear();
const broken = makeCloudLegacyReader({ currentUser: () => user, ownerUid: uid, fetchArchive: async () => ({ ...saved, sha256: '0'.repeat(64) }) });
await assert.rejects(() => broken.open('about'), /invalid-archive/);
let resolve;
const waiting = makeCloudLegacyReader({ currentUser: () => user, ownerUid: uid, fetchArchive: () => new Promise(done => { resolve = done; }) });
const pending = waiting.open('about');
user = null; waiting.clear(); resolve(saved);
assert.equal(await pending, null);
console.log('cloud legacy reader: ok');
