const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const browser = await chromium.launch({headless:true, channel:'msedge'});
  const page = await browser.newPage({viewport:{width:390,height:844}});
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.route('**/sync.js', r => r.fulfill({body:''}));
  await page.goto(pathToFileURL(path.resolve(__dirname, '../money/budget.html')).href);
  const house = page.locator('#need details').filter({has:page.locator('summary',{hasText:'住まい（'})});
  await house.locator('summary').click();
  await house.getByRole('button',{name:'内訳を追加',exact:true}).click();
  await house.locator('.part-name').nth(0).fill('家賃');
  await house.locator('.part-amount').nth(0).fill('100000');
  await house.getByRole('button',{name:'内訳を追加',exact:true}).click();
  await house.locator('.part-name').nth(1).fill('ローン利息');
  await house.locator('.part-amount').nth(1).fill('20000');
  assert.equal(await house.locator('.need-total').inputValue(),'120000');
  await house.getByRole('button',{name:'保存',exact:true}).click();
  assert.match(await page.locator('#tout').innerText(),/120,000/);
  assert.match(await house.locator('summary').innerText(),/120,000/);
  await page.reload();
  await house.locator('summary').click();
  assert.equal(await house.locator('.part-name').nth(1).inputValue(),'ローン利息');
  await house.getByRole('button',{name:'内訳を削除'}).nth(1).click();
  await house.getByRole('button',{name:'保存',exact:true}).click();
  assert.equal(await house.locator('.need-total').inputValue(),'100000');
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('hibiki-budget-v1')).expense.find(x=>/住/.test(x.name)).parts.length),1);
  const source = page.locator('#cout .row').filter({hasText:'住まい（'}).locator('.quick-amount');
  await source.fill('90000'); await source.dispatchEvent('change');
  assert.equal(await house.locator('.part-name').count(),0);
  assert.equal(await house.locator('.need-total').inputValue(),'90000');
  await house.getByRole('button',{name:'内訳を追加',exact:true}).click();
  assert.equal(await house.locator('.part-amount').nth(0).inputValue(),'90000');
  await house.getByRole('button',{name:'保存',exact:true}).click();
  assert.equal(await house.locator('.need-total').inputValue(),'90000');
  await page.screenshot({path:path.resolve(__dirname,'../budget-parts.png'), fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('Parts: live sum, persistence, graphs, deletion, direct override and preserving an existing total passed.');
})().catch(e=>{console.error(e);process.exitCode=1;});
