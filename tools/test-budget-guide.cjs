const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await page.route('**/sync.js', r => r.fulfill({ body: '' }));
  await page.goto(pathToFileURL(path.resolve(__dirname, '../money/budget.html')).href);
  const food = page.locator('#need details').filter({ has: page.locator('summary', { hasText: '食費' }) });
  assert.equal(await food.getAttribute('open'), null);
  await food.locator('summary').click();
  await food.locator('input').fill('123456');
  await food.locator('textarea').fill('食事の内訳メモ');
  await food.getByRole('button', { name: '保存', exact: true }).click();
  assert.match(await food.locator('summary').innerText(), /123,456/);
  assert.equal(await food.locator('textarea').inputValue(), '食事の内訳メモ');
  const hobby = page.locator('#need details').filter({ has: page.locator('summary', { hasText: '健康・運動' }) });
  await hobby.locator('summary').click();
  await hobby.locator('input').fill('5000');
  await hobby.locator('textarea').fill('初めての項目');
  await hobby.getByRole('button', { name: '保存', exact: true }).click();
  await hobby.getByRole('button', { name: '保存', exact: true }).click();
  const data = await page.evaluate(() => JSON.parse(localStorage.getItem('hibiki-budget-v1')));
  assert.equal(data.expense.filter(x => /健康/.test(x.name)).length, 1);
  assert.equal(data.expense.find(x => /食/.test(x.name)).memo, '食事の内訳メモ');
  await page.reload();
  await food.locator('summary').click();
  assert.equal(await food.locator('textarea').inputValue(), '食事の内訳メモ');
  await page.screenshot({ path: path.resolve(__dirname, '../budget-guide-edit.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await browser.close();
  console.log('Guide: accordion, edit, memo persistence, missing-category creation and duplicate prevention passed.');
})().catch(e => { console.error(e); process.exitCode = 1; });
